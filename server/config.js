    quoteOnKeywordReply: true,

    // 私聊（别人直接找它说话）——这是在对它说话，不该抽样，也不该被冷却拦住
    alwaysAnswerPrivate: true,
    privateCooldownMs: 1000,

    // ===== 🆕 识图（2026-09-22）=====
    //
    // 用户需求：「给 bot 增加识图功能，不然发表情包他都看不懂」
